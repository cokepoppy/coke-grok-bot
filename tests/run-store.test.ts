import test from 'node:test';
import assert from 'node:assert/strict';
import { randomUUID } from 'node:crypto';
import mysql from 'mysql2/promise';
import { TenantStore, type Session } from '../src/server/tenant-store.ts';
import { BotStore } from '../src/server/bot-store.ts';
import { RunStore } from '../src/server/run-store.ts';
import { WorkspaceFileStore } from '../src/server/file-store.ts';

const port = Number(process.env.COKE_GROK_TEST_MYSQL_PORT);
if (!port) throw new Error('Set COKE_GROK_TEST_MYSQL_PORT to a disposable local MySQL instance.');
test('runs are deduplicated, isolated, serialized per computer and never silently retried after lease expiry', async () => {
  const database = `grok_runs_${randomUUID().replaceAll('-','')}`;
  const admin = await mysql.createConnection({host:'127.0.0.1',port,user:'root'});
  await admin.query(`CREATE DATABASE \`${database}\``);
  const pool = mysql.createPool({host:'127.0.0.1',port,user:'root',database,timezone:'Z',connectionLimit:6});
  try {
    const identities = new TenantStore(pool); await identities.migrate();
    const bots = new BotStore(pool); await bots.migrate();
    const runs = new RunStore(pool),files=new WorkspaceFileStore(pool); await runs.migrate(); await runs.migrate();
    const a = await identities.signInGoogle({subject:'a',email:'a@example.test',name:'A'});
    const b = await identities.signInGoogle({subject:'b',email:'b@example.test',name:'B'});
    const session = (x:typeof a):Session => ({...x,email:'x@example.test',name:'X',role:'owner'});
    const sa = session(a), sb = session(b);
    const bot1 = await bots.create(sa,{name:'A1',shape:'hex',color:'#abcdef'});
    const bot2 = await bots.create(sa,{name:'A2',shape:'round',color:'#abcdef'});
    const bot3 = await bots.create(sb,{name:'B',shape:'round',color:'#abcdef'});
    const requestId = randomUUID();
    const [first, duplicate] = await Promise.all([runs.create(sa,bot1.id,requestId,'work one'),runs.create(sa,bot1.id,requestId,'work one')]);
    assert.ok(first && duplicate); assert.equal(first.id,duplicate.id);
    await assert.rejects(runs.create(sa,bot1.id,requestId,'different'));
    assert.equal(await runs.create(sb,bot1.id,randomUUID(),'intrude'),null);
    assert.equal(await runs.list(sb,bot1.id),null);
    assert.equal(await runs.events(sb,first.id),null);
    const second = await runs.create(sa,bot2.id,randomUUID(),'work two');
    const other = await runs.create(sb,bot3.id,randomUUID(),'other');
    assert.ok(second && other);
    const [claim1, claim2] = await Promise.all([runs.claimNext(sa,10),runs.claimNext(sa,10)]);
    const claim = claim1 || claim2; assert.ok(claim); assert.equal(Number(Boolean(claim1))+Number(Boolean(claim2)),1);
    const otherClaim = await runs.claimNext(sb,10); assert.ok(otherClaim);
    assert.equal(await runs.hasLiveLease(sa,claim.run.id,claim.leaseId),true);
    assert.equal(await runs.hasLiveLease(sb,claim.run.id,claim.leaseId),false);
    assert.equal(await runs.hasLiveLease(sa,claim.run.id,randomUUID()),false);
    assert.equal(await runs.finish(claim.run.id,randomUUID(),'completed','forged'),false);
    const auditWithUnsafeExtras={engine:'pi',model:'deepseek-v4.1-flash',modelCompleted:true,calls:[{tool:'computer_browser',action:'navigate',outcome:'succeeded',url:'https://example.test/private?access_token=never-store'}],truncated:false,apiKey:'never-store'};
    assert.equal(await runs.finish(claim.run.id,claim.leaseId,'completed','done',[],auditWithUnsafeExtras),true);
    const persistedAudit=(await runs.list(sa,claim.run.botId))?.find(run=>run.id===claim.run.id)?.executionAudit;
    assert.deepEqual(persistedAudit,{engine:'pi',model:'deepseek-v4.1-flash',modelCompleted:true,calls:[{tool:'computer_browser',action:'navigate',outcome:'succeeded'}],truncated:false});
    const [auditRows]=await pool.execute<mysql.RowDataPacket[]>('SELECT CAST(execution_audit AS CHAR) AS audit FROM agent_runs WHERE id=?',[claim.run.id]);
    assert.equal(String(auditRows[0].audit).includes('access_token'),false);
    assert.equal(String(auditRows[0].audit).includes('https://'),false);
    assert.equal(String(auditRows[0].audit).includes('apiKey'),false);
    assert.equal(await runs.hasLiveLease(sa,claim.run.id,claim.leaseId),false);
    assert.equal(await runs.finish(claim.run.id,claim.leaseId,'completed','duplicate'),false);
    const next = await runs.claimNext(sa,1); assert.ok(next); assert.notEqual(next.run.id,claim.run.id);
    await new Promise(resolve => setTimeout(resolve,1200));
    assert.equal(await runs.markExpiredUnknown(),1);
    assert.equal(await runs.finish(next.run.id,next.leaseId,'completed','late'),false);
    assert.equal(await runs.claimNext(sa,10),null);
    assert.deepEqual((await runs.events(sa,next.run.id))?.map(event => event.status),['queued','running','unknown']);
    const uncertain=(await runs.list(sa,next.run.botId))?.find(run => run.id === next.run.id);
    assert.equal(uncertain?.status,'unknown'); assert.equal(uncertain?.recoveryState,'pending');
    assert.equal(await runs.resolveUnknown(sb,next.run.id,'acknowledge'),null);
    assert.equal((await runs.queuedOwners(10)).some(owner=>owner.userId===sa.userId),false);
    const retryResults=await Promise.all([runs.resolveUnknown(sa,next.run.id,'retry'),runs.resolveUnknown(sa,next.run.id,'retry')]);
    const retry=retryResults[0];assert.ok(retry?.run);assert.equal(retry.run.status,'queued');assert.equal(retry.run.prompt,next.run.prompt);assert.equal(retryResults[1]?.run?.id,retry.run.id);
    assert.equal((await runs.list(sa,next.run.botId))?.find(run=>run.id===next.run.id)?.recoveryState,'retried');
    assert.equal((await runs.queuedOwners(10)).some(owner=>owner.userId===sa.userId),true);
    const retryClaim=await runs.claimNext(sa,10);assert.equal(retryClaim?.run.id,retry.run.id);
    assert.equal(await runs.finish(retry.run.id,retryClaim!.leaseId,'completed','explicit retry done'),true);

    const ackRequest=randomUUID(),ackQueued=await runs.create(sa,bot1.id,ackRequest,'acknowledge safely');assert.ok(ackQueued);
    const ackClaim=await runs.claimNext(sa,10);assert.ok(ackClaim);assert.equal(ackClaim.run.id,ackQueued.id);
    assert.equal(await runs.markUnknown(ackClaim.run.id,ackClaim.leaseId,'agent_paused_for_control'),true);
    assert.equal((await runs.list(sa,bot1.id))?.find(run=>run.id===ackClaim.run.id)?.diagnosticCode,'agent_paused_for_control');
    const afterAck=await runs.create(sa,bot2.id,randomUUID(),'continue after review');assert.ok(afterAck);assert.equal(await runs.claimNext(sa,10),null);
    const acknowledged=await runs.resolveUnknown(sa,ackClaim.run.id,'acknowledge');assert.deepEqual(acknowledged,{decision:'acknowledge',run:null});
    assert.deepEqual(await runs.resolveUnknown(sa,ackClaim.run.id,'acknowledge'),{decision:'acknowledge',run:null});
    assert.equal((await runs.list(sa,bot1.id))?.find(run=>run.id===ackClaim.run.id)?.recoveryState,'acknowledged');
    const resumed=await runs.claimNext(sa,10);assert.equal(resumed?.run.id,afterAck.id);assert.equal(await runs.finish(afterAck.id,resumed!.leaseId,'completed','continued'),true);
    assert.equal(await runs.finish(otherClaim.run.id,otherClaim.leaseId,'completed','other done'),true);

    const inputBytes=Buffer.from('read from the user attachment'),inputHash=await import('node:crypto').then(({createHash})=>createHash('sha256').update(inputBytes).digest('hex'));
    const inputFile=files.newUpload(bot1.id,'source notes.txt','text/plain',inputBytes.length,inputHash);
    assert.equal(await files.saveUpload(sa,inputFile),true);assert.equal(await files.saveUpload(sb,inputFile),false);
    const attachedRequestId=randomUUID(),attachedRun=await runs.create(sa,bot1.id,attachedRequestId,'Summarize this file',[inputFile.id]);assert.ok(attachedRun);assert.equal(attachedRun.files[0].id,inputFile.id);assert.equal(attachedRun.files[0].storageKey,inputFile.storageKey);
    const duplicateAttached=await runs.create(sa,bot1.id,attachedRequestId,'Summarize this file',[inputFile.id]);assert.equal(duplicateAttached?.id,attachedRun.id);
    await assert.rejects(runs.create(sa,bot1.id,attachedRequestId,'Summarize this file',[]));
    await assert.rejects(runs.create(sb,bot3.id,randomUUID(),'Cross-user file',[inputFile.id]));
    const attachedClaim=await runs.claimNext(sa,30);assert.equal(attachedClaim?.run.id,attachedRun.id);assert.equal(attachedClaim?.run.files[0].id,inputFile.id);
    const outputBytes=Buffer.from('file generated by the agent');
    assert.equal(await runs.finish(attachedRun.id,attachedClaim!.leaseId,'completed','Created a text result.',[{name:'summary.txt',mimeType:'text/plain',size:outputBytes.length,sha256:await import('node:crypto').then(({createHash})=>createHash('sha256').update(outputBytes).digest('hex')),storageKey:`tasks/${attachedRun.id}/artifacts/summary.txt` }]),true);
    const completedFiles=(await runs.list(sa,bot1.id))?.find(run=>run.id===attachedRun.id)?.files||[];assert.deepEqual(completedFiles.map(file=>file.kind),['input','output']);
    const outputFile=completedFiles.find(file=>file.kind==='output')!;assert.equal((await runs.fileForDownload(sa,outputFile.id))?.storageKey,`tasks/${attachedRun.id}/artifacts/summary.txt`);assert.equal(await runs.fileForDownload(sb,outputFile.id),null);

    const mentionRequestId=randomUUID(),mentionPrompt='Please ask @A2 to investigate this.';
    const mentionRun=await runs.create(sa,bot1.id,mentionRequestId,mentionPrompt,undefined,[bot2.id]);assert.ok(mentionRun);
    assert.equal(mentionRun.prompt,mentionPrompt);
    assert.deepEqual(mentionRun.runtimeContext,{kind:'bot-mentions',targets:[{id:bot2.id,name:'A2',label:''}]});
    await assert.rejects(runs.create(sa,bot1.id,mentionRequestId,mentionPrompt),/Request ID already used/);
    await assert.rejects(runs.create(sa,bot1.id,randomUUID(),mentionPrompt,undefined,[bot1.id]),/Invalid Bot mention targets/);
    await assert.rejects(runs.create(sa,bot1.id,randomUUID(),mentionPrompt,undefined,[bot3.id]),/Invalid Bot mention targets/);
    const mentionClaim=await runs.claimNext(sa,30);assert.equal(mentionClaim?.run.id,mentionRun.id);
    assert.equal(mentionClaim?.run.prompt,mentionPrompt);
    assert.deepEqual(mentionClaim?.run.runtimeContext,mentionRun.runtimeContext);
    assert.equal(await runs.finish(mentionRun.id,mentionClaim!.leaseId,'completed','A2 returned its findings.'),true);

    const handoffBot=await bots.create(sa,{name:'Sign-in Handoff',shape:'hex',color:'#abcdef'});
    const handoffPrompt='Open Gmail and stop at sign-in so I can take control.';
    const handoffRun=await runs.create(sa,handoffBot.id,randomUUID(),handoffPrompt);assert.ok(handoffRun);
    const handoffClaim=await runs.claimNext({...sa,botId:handoffBot.id},30);assert.equal(handoffClaim?.run.id,handoffRun.id);
    assert.deepEqual(handoffClaim?.run.previousPrompts,[]);
    assert.equal(await runs.finish(handoffRun.id,handoffClaim!.leaseId,'completed','Stopped at sign-in.'),true);
    const continuation=await runs.create(sa,handoffBot.id,randomUUID(),'Do not ask me for approval every step; open it directly.');assert.ok(continuation);
    const continuationClaim=await runs.claimNext({...sa,botId:handoffBot.id},30);assert.equal(continuationClaim?.run.id,continuation.id);
    assert.deepEqual(continuationClaim?.run.previousPrompts,[handoffPrompt]);
    assert.equal(await runs.finish(continuation.id,continuationClaim!.leaseId,'completed','Continued.'),true);
    const unrelated=await runs.create(sa,bot2.id,randomUUID(),'Do not ask me for approval every step; open it directly.');assert.ok(unrelated);
    const unrelatedClaim=await runs.claimNext({...sa,botId:bot2.id},30);assert.equal(unrelatedClaim?.run.id,unrelated.id);
    assert.equal(unrelatedClaim?.run.previousPrompts?.includes(handoffPrompt),false, 'Prior prompts must remain isolated to the same Bot');
  } finally { await pool.end(); await admin.query(`DROP DATABASE \`${database}\``); await admin.end(); }
});

test('separate Bot screens can be leased in parallel while each Bot queue remains serial',async()=>{
  const database=`grok_screen_runs_${randomUUID().replaceAll('-','')}`,admin=await mysql.createConnection({host:'127.0.0.1',port,user:'root'});
  await admin.query(`CREATE DATABASE \`${database}\``);
  const pool=mysql.createPool({host:'127.0.0.1',port,user:'root',database,timezone:'Z',connectionLimit:8});
  try{
    const identities=new TenantStore(pool);await identities.migrate();const bots=new BotStore(pool);await bots.migrate();const runs=new RunStore(pool);await runs.migrate();
    const identity=await identities.signInGoogle({subject:'bot-screens',email:'screens@example.test',name:'Screen Owner'}),session:Session={...identity,email:'screens@example.test',name:'Screen Owner',role:'owner'};
    const botA=await bots.create(session,{name:'A',shape:'hex',color:'#abcdef'}),botB=await bots.create(session,{name:'B',shape:'round',color:'#abcdef'});
    const first=await runs.create(session,botA.id,randomUUID(),'A first'),queuedSame=await runs.create(session,botA.id,randomUUID(),'A second'),parallel=await runs.create(session,botB.id,randomUUID(),'B first'),queuedB=await runs.create(session,botB.id,randomUUID(),'B second');
    assert.ok(first&&queuedSame&&parallel&&queuedB);
    const screens=await runs.queuedScreens(10);assert.deepEqual(new Set(screens.map(screen=>screen.botId)),new Set([botA.id,botB.id]));
    const [claimA,claimB]=await Promise.all([runs.claimNext({...session,botId:botA.id},30),runs.claimNext({...session,botId:botB.id},30)]);
    assert.equal(claimA?.run.id,first.id);assert.equal(claimB?.run.id,parallel.id);
    assert.equal(await runs.claimNext({...session,botId:botA.id},30),null);
    assert.equal(await runs.hasLiveLease(session,claimA!.run.id,claimA!.leaseId,botA.id),true);
    assert.equal(await runs.hasLiveLease(session,claimA!.run.id,claimA!.leaseId,botB.id),false);
    assert.equal(await runs.markUnknown(claimA!.run.id,claimA!.leaseId,'agent_paused_for_control'),true);
    assert.deepEqual((await runs.queuedScreens(10)).map(screen=>screen.botId),[]);
    assert.equal(await runs.finish(claimB!.run.id,claimB!.leaseId,'completed','B finished'),true);
    assert.deepEqual((await runs.queuedScreens(10)).map(screen=>screen.botId),[botB.id]);
    const nextB=await runs.claimNext({...session,botId:botB.id},30);assert.equal(nextB?.run.id,queuedB.id);
    assert.equal(await runs.finish(nextB!.run.id,nextB!.leaseId,'completed','B second finished'),true);
    await runs.resolveUnknown(session,claimA!.run.id,'acknowledge');
    assert.deepEqual((await runs.queuedScreens(10)).map(screen=>screen.botId),[botA.id]);
    const nextA=await runs.claimNext({...session,botId:botA.id},30);assert.equal(nextA?.run.id,queuedSame.id);
    assert.equal(await runs.finish(nextA!.run.id,nextA!.leaseId,'completed','A second finished'),true);
  }finally{await pool.end();await admin.query(`DROP DATABASE \`${database}\``);await admin.end()}
});
